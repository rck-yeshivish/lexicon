"""Rebuild lexicon/INDEX.md from the entries.
  python lexicon/tools/build_index.py

The index is HEBREW-FIRST, because that is the direction the guide is used in:
you are looking at a Hebrew word and need its English. Part 1 is a headword
lookup, one line per Hebrew word, in alef-bet order. Part 2 is one block per
entry with its full ruling, never truncated.
"""
import re, pathlib, datetime, unicodedata

ROOT = pathlib.Path(__file__).resolve().parents[1]
ENTRIES = ROOT / "entries"
NIKUD = re.compile("[֑-ׇ]")


def strip_nikud(s):
    return NIKUD.sub("", unicodedata.normalize("NFC", s)).strip()


def front_matter(text):
    m = re.match(r"---\n(.*?)\n---", text, re.S)
    fm, key = {}, None
    if not m:
        return fm
    for line in m.group(1).splitlines():
        if re.match(r"^\s+-\s", line) and key:
            if not isinstance(fm.get(key), list):
                fm[key] = []
            fm[key].append(line.strip()[2:].strip())
            continue
        mm = re.match(r"^([A-Za-z_]+):\s*(.*)$", line)
        if mm:
            key, val = mm.group(1), mm.group(2).split("  #")[0].strip()
            if val.startswith("[") and val.endswith("]"):
                fm[key] = [v.strip() for v in val[1:-1].split(",") if v.strip()]
            elif val == "":
                fm[key] = []
            else:
                fm[key] = val
    return fm


def word_block(text):
    """Parse the optional per-word `words:` block.

    Each item gives one Hebrew word its OWN English and the one line that tells
    it apart from its neighbours, so the headword table can be precise instead
    of repeating the whole cluster's glosses against every word.
    """
    m = re.search(r"^words:\s*\n((?:\s+(?:-\s+)?\w+:.*\n?)+)", text, re.M)
    if not m:
        return []
    items, cur = [], None
    for line in m.group(1).splitlines():
        mm = re.match(r"^\s+-\s+(\w+):\s*(.*)$", line)
        if mm:
            if cur:
                items.append(cur)
            cur = {mm.group(1): mm.group(2).strip()}
            continue
        mm = re.match(r"^\s+(\w+):\s*(.*)$", line)
        if mm and cur is not None:
            cur[mm.group(1)] = mm.group(2).strip()
    if cur:
        items.append(cur)
    return [i for i in items if i.get("he")]


def section(text, heading):
    m = re.search(rf"## {heading}\s*\n(.*?)(?:\n## |\Z)", text, re.S)
    return m.group(1).strip() if m else ""


def one_paragraph(s):
    """Collapse to a single flowed paragraph so an index line is never cut."""
    return " ".join(s.split())


entries = []
for p in sorted(ENTRIES.glob("*.md")):
    t = p.read_text(encoding="utf-8")
    fm = front_matter(t)
    entries.append({
        "file": p.name,
        "cluster": fm.get("cluster", p.stem),
        "hebrew": [strip_nikud(h) for h in fm.get("hebrew", []) if strip_nikud(h)],
        "translit": fm.get("translit", []),
        "english": fm.get("english", []),
        "domain": fm.get("domain", "other"),
        "status": fm.get("status", "draft"),
        "bottom": one_paragraph(section(t, "Bottom line")),
        # Whole, not flowed into one line: it is the one place the guide
        # tells anyone how to translate, and it carries lists.
        "rendering": section(t, "Rendering guidance"),
        "words": word_block(t),
    })

# Part 1: Hebrew headword lookup
heads = []
for e in entries:
    per = {strip_nikud(w["he"]): w for w in e["words"]}
    for h in e["hebrew"]:
        w = per.pop(h, None)
        heads.append((h, e, w))
    for h, w in per.items():          # a word listed only in the words: block
        heads.append((h, e, w))
heads.sort(key=lambda r: (r[0], r[1]["cluster"]))
detailed = sum(1 for _, _, w in heads if w)

out = ["# Lexicon index", "",
       f"GENERATED by tools/build_index.py on {datetime.date.today()}. "
       f"{len(entries)} entries, {len(heads)} Hebrew headwords. Do not edit by hand.", "",
       "**How to use this file.** It is a table of contents, not the guide. Find your Hebrew",
       "word in the headword list, open the entry it points to, and apply that entry's",
       "*Bottom line*. The entry is where the words are actually told apart, with each",
       "distinction attributed to the authority who makes it, and disagreements between",
       "authorities laid out rather than flattened. Part 2 below gives each entry's full",
       "ruling so you can often decide without opening anything.", "",
       "Each entry in Part 2 carries its *Bottom line* and then its *Rendering guidance*.",
       "The Bottom line says what the words mean and how the authorities separate them;",
       "the Rendering guidance is the one place in this guide that says how to put them",
       "into English, and it is not on the website, only here.", "",
       "---", "",
       "## Part 1: Hebrew headwords (alef-bet order)", "",
       "Where a row names an English rendering, that rendering is that word's own.",
       "Where it says *see entry*, the entry tells the cluster apart in prose and in",
       "its Bottom line; open it rather than guessing from the neighbouring words.", "",
       "| Hebrew | translit | English | what sets it apart | entry |", "|---|---|---|---|---|"]
for h, e, w in heads:
    if w:
        out.append(f"| {h} | {w.get('tr', '')} | **{w.get('en', '')}** | {w.get('distinct', '')} "
                   f"| [{e['file']}](entries/{e['file']}) |")
    else:
        # No per-word ruling for this word. Do NOT print the cluster's glosses
        # against it: that reads as a definition and is often the neighbour's
        # word, not this one. Send the reader to the entry instead.
        out.append(f"| {h} | | see entry | one of the *{e['cluster']}* words "
                   f"| [{e['file']}](entries/{e['file']}) |")

# Part 2: full rulings, grouped by domain
out += ["", "---", "", "## Part 2: the entries, with their full rulings", ""]
cur = None
for e in sorted(entries, key=lambda x: (x["domain"], x["cluster"])):
    if e["domain"] != cur:
        out += ["", f"### {e['domain']}", ""]
        cur = e["domain"]
    heb = " / ".join(e["hebrew"])
    tr = ", ".join(e["translit"][:8])
    out += [f"**{heb}** — {e['cluster']} | {tr} | {e['status']} | [{e['file']}](entries/{e['file']})", ""]
    if e["bottom"]:
        out += [e["bottom"], ""]
    if e["rendering"]:
        out += ["**Rendering guidance.**", "", e["rendering"], ""]

(ROOT / "INDEX.md").write_text("\n".join(out) + "\n", encoding="utf-8")
print(f"INDEX.md: {len(entries)} entries, {len(heads)} Hebrew headwords "
      f"({detailed} with a per-word ruling), no truncation")
