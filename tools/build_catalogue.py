"""Rebuild sources/whats-in-a-word/catalogue.md: every article of the column,
the terms it treats, both URLs, and which lexicon entry (if any) draws on it.
  python lexicon/tools/build_catalogue.py

Terms come from two places: the Times of Israel mirror's titles (which name the
words, e.g. "Facing Death - mitah, niftar") matched to the ohr.edu article by
those words occurring in its body (the mirror reposts a column roughly two years later); and, as a fallback, the
transliterated words the article itself italicises most often.
"""
import json, re, pathlib, datetime, email.utils, collections

ROOT = pathlib.Path(__file__).resolve().parents[1]
SRC = ROOT / "sources" / "whats-in-a-word"
RAW = SRC / "raw"
ohr = json.load(open(SRC / "catalogue.json", encoding="utf-8"))
toi = json.load(open(SRC / "toi_catalogue.json", encoding="utf-8"))

STOP = set("""the a an and or of to in is it that this as for with on by from at be are was were not but
which who whom his her its their our your my we they he she i you one two three also than then so if
what when where how all any some such very more most other into out up down over under here there
parshat parsha parshas part word words hebrew english bible torah rabbi rav reb see cf ibid e.g i.e
vs like lit literally means meaning mean""".split())


def italics(text):
    return [w.lower().strip(" ,.;:()[]\"'") for w in re.findall(r"\*([^*\n]{2,40})\*", text)]


def looks_hebrew_translit(w):
    return bool(re.fullmatch(r"[a-z][a-z'\-]{2,}", w)) and w not in STOP


bodies = {}
for a in ohr:
    p = RAW / f"{a['id']}-{a['slug']}.md"
    a["raw"] = p.exists()
    a["day"] = datetime.date.fromisoformat(a["date"])
    if a["raw"]:
        t = p.read_text(encoding="utf-8")
        body = t.split("\n---\n", 1)[-1]
        bodies[a["id"]] = body.lower()
        cnt = collections.Counter(w for w in italics(body) if looks_hebrew_translit(w) and " " not in w)
        a["auto_terms"] = [w for w, c in cnt.most_common(12) if c >= 3][:6]
    else:
        a["auto_terms"] = []

for r in toi:
    parts = re.split(r"\s[–—-]\s", r["title"], maxsplit=1)
    r["core"] = parts[0].strip()
    r["terms"] = parts[1].strip() if len(parts) > 1 else ""
    r["day"] = email.utils.parsedate_to_datetime(r["date"]).date()
    r["words"] = [w.strip().lower() for w in re.split(r",|\band\b|&|/", r["terms"]) if len(w.strip()) > 2]

used = set()
for a in sorted(ohr, key=lambda x: x["day"]):
    a["toi"] = None
    if a["id"] not in bodies:
        continue
    body = bodies[a["id"]]
    best, score = None, 0
    for r in toi:
        if r["url"] in used or not r["words"] or abs((r["day"] - a["day"]).days) > 1300:
            continue
        hits = sum(1 for w in r["words"] if re.sub(r"[^a-z]", "", w) and re.sub(r"[^a-z]", "", w) in body)
        sc = hits / len(r["words"])
        if sc > score or (sc == score and best and abs((r["day"] - a["day"]).days) < abs((best["day"] - a["day"]).days)):
            best, score = r, sc
    if best and score >= 0.75:
        a["toi"] = best
        used.add(best["url"])

entry_of = {}
for p in (ROOT / "entries").glob("*.md"):
    for m in re.finditer(r"wiaw:(\d+)", p.read_text(encoding="utf-8")):
        entry_of.setdefault(int(m.group(1)), []).append(p.name)

out = ["# What's in a Word? catalogue", "",
       f"GENERATED by tools/build_catalogue.py on {datetime.date.today()}. Rabbi Reuven Chaim Klein's column "
       f"(Ohr Somayach), {len(ohr)} articles from the ohr.edu listing. id = the API id used in entries as "
       "wiaw:<id> (not the legacy ohr.edu/NNNN number). terms = from the Times of Israel mirror's title when "
       "matched (TOI link), else the words the article italicises most (marked ~). raw = harvested text in raw/. "
       "entry = lexicon entry drawing on it. Do not edit by hand.", "",
       "| id | date | title | terms | raw | entry |", "|---|---|---|---|---|---|"]
for a in sorted(ohr, key=lambda x: x["day"], reverse=True):
    if a["toi"]:
        terms = a["toi"]["terms"]
        link = f" ([TOI]({a['toi']['url']}))"
    else:
        terms = ("~ " + ", ".join(a["auto_terms"])) if a["auto_terms"] else ""
        link = ""
    ent = ", ".join(entry_of.get(a["id"], []))
    out.append(f"| {a['id']} | {a['date']} | [{a['title']}]({a['url']}){link} | {terms} | {'yes' if a['raw'] else ''} | {ent} |")

newest = max(a["day"] for a in ohr)
tail = [r for r in toi if r["url"] not in used and r["day"] > newest]
if tail:
    out += ["", "## Newer than the ohr.edu listing (Times of Israel only)", "",
            "Not in the API harvest; fetch by URL when needed (curl is blocked there, WebFetch works).", "",
            "| date | title | terms | url |", "|---|---|---|---|"]
    for r in sorted(tail, key=lambda x: x["day"], reverse=True):
        out.append(f"| {r['day']} | {r['core']} | {r['terms']} | {r['url']} |")
unmatched = [r for r in toi if r["url"] not in used and r not in tail]
out += ["", f"Unmatched Times of Israel posts (no confident match to an ohr.edu article): {len(unmatched)}. "
            "Same column; match by hand if a term is needed.", ""]
for r in sorted(unmatched, key=lambda x: x["day"], reverse=True):
    out.append(f"- {r['day']} | {r['title']} | {r['url']}")
(SRC / "catalogue.md").write_text("\n".join(out) + "\n", encoding="utf-8")
print(f"catalogue.md: {len(ohr)} ohr articles ({sum(a['raw'] for a in ohr)} raw), {len(used)} matched to TOI, "
      f"{len(tail)} TOI-only newer, {len(unmatched)} TOI unmatched")
